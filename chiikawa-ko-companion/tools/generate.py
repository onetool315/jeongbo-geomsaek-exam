def img(size=16):
    return Image.new("RGBA", (size, size), (0, 0, 0, 0))


def save(im, rel):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    im.save(path)


def px(d, pts, c):
    for x, y in pts:
        d.point((x, y), fill=c)


