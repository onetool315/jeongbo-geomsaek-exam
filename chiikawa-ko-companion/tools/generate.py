def block(rel, base, accent, kind):
    im = Image.new("RGBA", (16, 16), base)
    d = ImageDraw.Draw(im)
    d.rectangle((0, 0, 15, 15), outline=accent)
    if kind == "board":
        d.rectangle((2, 2, 13, 13), outline=(90, 60, 30, 255))
        for (x, y) in [(3, 3), (9, 3), (3, 8), (9, 8)]:
            d.rectangle((x, y, x + 3, y + 3), fill=(250, 245, 225, 255), outline=(190, 170, 120, 255))
    elif kind == "desk":
        d.rectangle((0, 0, 15, 5), fill=(235, 215, 170, 255), outline=accent)
        d.rectangle((2, 7, 4, 15), fill=accent)
        d.rectangle((11, 7, 13, 15), fill=accent)
        d.rectangle((5, 2, 10, 3), fill=(60, 60, 60, 255))
    elif kind == "shop":
        for i in range(0, 16, 4):
            d.rectangle((i, 0, i + 1, 5), fill=(240, 240, 240, 255))
            d.rectangle((i + 2, 0, i + 3, 5), fill=(210, 50, 60, 255))
        d.rectangle((2, 8, 13, 13), fill=(250, 230, 180, 255), outline=accent)
        d.ellipse((6, 9, 9, 12), fill=(60, 200, 110, 255))
    return im


